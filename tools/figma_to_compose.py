#!/usr/bin/env python3
"""Extract named Figma CSS layers into a deterministic design manifest and Compose specs.

Usage:
  python tools/figma_to_compose.py --css pix.css --svg pix.svg --out generated
  python tools/figma_to_compose.py --css pix.css --svg pix.svg --out generated --scale 3

The default scale (3 px per dp) matches a 1080px-wide export intended for a 360dp canvas.
No source design files are modified.
"""
from __future__ import annotations

import argparse
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

SECTION = re.compile(r"^/\*\s*(.*?)\s*\*/\s*$")
DECL = re.compile(r"^\s*([a-zA-Z-]+)\s*:\s*(.*?)\s*;\s*$")


def parse_css(path: Path, scale: float) -> list[dict[str, Any]]:
    sections: list[dict[str, Any]] = []
    current: dict[str, Any] | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        heading = SECTION.match(line)
        if heading:
            label = heading.group(1).strip()
            if label in {"Auto layout", "Inside auto layout"}:
                continue
            current = {"name": label, "css": {}}
            sections.append(current)
            continue
        if current is None:
            continue
        declaration = DECL.match(line)
        if declaration:
            current["css"][declaration.group(1)] = declaration.group(2).strip()

    for item in sections:
        css = item["css"]
        for key in ("width", "height", "left", "top", "gap"):
            raw = css.get(key)
            if raw:
                match = re.match(r"^(-?\d+(?:\.\d+)?)px$", raw)
                if match:
                    item[key + "Px"] = float(match.group(1))
                    item[key + "Dp"] = round(float(match.group(1)) / scale, 4)
        item["backgroundColor"] = css.get("background") if css.get("background", "").startswith("#") else None
        item["borderRadius"] = css.get("border-radius")
        item["border"] = css.get("border")
        item["fontFamily"] = css.get("font-family")
        item["fontSize"] = css.get("font-size")
        item["fontWeight"] = css.get("font-weight")
        item["textColor"] = css.get("color")
        item["gradient"] = css.get("background") if "gradient(" in css.get("background", "") else None
    return sections


def inspect_svg(path: Path) -> dict[str, Any]:
    result: dict[str, Any] = {"file": path.name, "bytes": path.stat().st_size, "viewBox": None, "namedGroups": []}
    try:
        root = ET.parse(path).getroot()
        result["viewBox"] = root.attrib.get("viewBox")
        for node in root.iter():
            tag = node.tag.rsplit("}", 1)[-1]
            if tag != "g":
                continue
            label = (node.attrib.get("id") or node.attrib.get("{http://www.inkscape.org/namespaces/inkscape}label")
                     or node.attrib.get("data-name"))
            if label:
                result["namedGroups"].append(label)
    except (ET.ParseError, OSError) as exc:
        result["parseWarning"] = str(exc)
    return result


def kotlin_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def emit_kotlin(sections: list[dict[str, Any]], scale: float, out: Path) -> None:
    lines = [
        "// Generated by tools/figma_to_compose.py. Do not edit by hand.",
        "package com.example.pix.generated",
        "",
        "data class PixLayerSpec(",
        '    val name: String, val xDp: Float? = null, val yDp: Float? = null,',
        '    val widthDp: Float? = null, val heightDp: Float? = null,',
        '    val background: String? = null, val textColor: String? = null,',
        '    val radiusPx: String? = null, val border: String? = null,',
        '    val fontSizePx: String? = null, val fontWeight: String? = null,',
        '    val gradient: String? = null',
        ")",
        "",
        f"const val PIX_EXPORT_PX_PER_DP: Float = {scale}f",
        "const val PIX_TEMPLATE_SCREEN_WIDTH_PX: Float = 1080f",
        "const val PIX_TEMPLATE_SCREEN_HEIGHT_PX: Float = 2115f",
        "const val PIX_PROFILE_SCREEN_WIDTH_PX: Float = 1080f",
        "const val PIX_PROFILE_SCREEN_HEIGHT_PX: Float = 2106f",
        "",
        "val PixLayers = listOf(",
    ]
    for item in sections:
        lines.append("    PixLayerSpec(")
        lines.append(f'        name = "{kotlin_string(item["name"])}",')
        for source, target in (("leftDp", "xDp"), ("topDp", "yDp"), ("widthDp", "widthDp"), ("heightDp", "heightDp")):
            if source in item:
                lines.append(f"        {target} = {item[source]}f,")
        for source, target in (("backgroundColor", "background"), ("textColor", "textColor"),
                               ("borderRadius", "radiusPx"), ("border", "border"),
                               ("fontSize", "fontSizePx"), ("fontWeight", "fontWeight"),
                               ("gradient", "gradient")):
            if item.get(source):
                lines.append(f'        {target} = "{kotlin_string(str(item[source]))}",')
        lines.append("    ),")
    lines += [")", ""]
    (out / "PixDesignSpec.kt").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--css", type=Path, required=True)
    parser.add_argument("--svg", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("generated"))
    parser.add_argument("--scale", type=float, default=3.0, help="Figma export px per Android dp")
    args = parser.parse_args()
    if args.scale <= 0:
        parser.error("--scale must be greater than zero")
    args.out.mkdir(parents=True, exist_ok=True)
    layers = parse_css(args.css, args.scale)
    manifest = {
        "source": {"css": args.css.name, "svg": inspect_svg(args.svg)},
        "scalePxPerDp": args.scale,
        "screens": [
            {"name": "Template browsing", "widthPx": 1080, "heightPx": 2115},
            {"name": "Profile", "widthPx": 1080, "heightPx": 2106},
        ],
        "layerCount": len(layers),
        "layers": layers,
        "notes": [
            "CSS positions and dimensions are preserved in source px and converted dp.",
            "CSS does not contain the actual text/image pixels; those remain in the SVG source.",
            "Review SVG clipping, masks, filters, embedded raster images and font outlines before claiming pixel parity.",
            "The generated Kotlin file is a typed design-spec layer, not a complete screen implementation."
        ],
    }
    (args.out / "pix-design-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    emit_kotlin(layers, args.scale, args.out)
    print(f"Extracted {len(layers)} named CSS sections into {args.out}")


if __name__ == "__main__":
    main()
